/**
 * Regenerates the progress block in ROADMAP.md (task A9, DQ-5).
 *
 *   pnpm roadmap          rewrite the block from the task lines
 *   pnpm roadmap --check  exit 1 if the block does not match the tasks (CI)
 *
 * Parsing is line based and deliberately strict: a task line looks like
 *   - [x] **A7** [P0] text ... Est: 3h.
 * and a phase header looks like
 *   ### Phase A: Foundations (2 to 3 Nov)
 * Anything that does not match is ignored, so prose checkboxes are not counted.
 * Only task lines under a `### Phase` header count: the update protocol at the
 * top of ROADMAP.md shows a sample task line in the same format.
 * `[~]`, `[!]`, `[-]` and `[ ]` all count as "not done" for readiness, which is
 * the honest reading: only `[x]` with an Evidence line is finished.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ROADMAP = "ROADMAP.md";
const START = "<!-- progress:start (generated by `pnpm roadmap`; do not edit by hand) -->";
const END = "<!-- progress:end -->";

type Task = {
  status: string;
  id: string;
  priority: "P0" | "P1";
  hours: number;
  phase: string;
};

const TASK_LINE = /^- \[( |x|~|!|-)\] \*\*([A-Z]+-?\d+|\w+)\*\* \[(P0|P1)\] .*?Est: ([0-9.]+)h/;
const PHASE_LINE = /^### Phase ([A-Z]):/;

export function parseTasks(lines: readonly string[]): Task[] {
  const tasks: Task[] = [];
  // null until the first phase header. The update protocol near the top of the
  // file contains a sample task line in exactly this format, and counting it
  // would invent a phase and a P0 task.
  let phase: string | null = null;
  for (const line of lines) {
    const phaseMatch = PHASE_LINE.exec(line);
    if (phaseMatch !== null) {
      phase = `Phase ${phaseMatch[1]}`;
      continue;
    }
    const taskMatch = TASK_LINE.exec(line);
    if (taskMatch === null || phase === null) {
      continue;
    }
    const [, status = " ", id = "?", priority = "P0", hours = "0"] = taskMatch;
    tasks.push({
      status,
      id,
      priority: priority === "P1" ? "P1" : "P0",
      hours: Number(hours),
      phase,
    });
  }
  return tasks;
}

export function renderBlock(tasks: readonly Task[]): string {
  const phases = [...new Set(tasks.map((task) => task.phase))];
  const done = (task: Task) => task.status === "x";
  const rows = phases.map((phase) => {
    const inPhase = tasks.filter((task) => task.phase === phase);
    const p0 = inPhase.filter((task) => task.priority === "P0");
    const p1 = inPhase.filter((task) => task.priority === "P1");
    // The column is labelled "P0 hours left", so P1 hours stay out of it.
    const openHours = p0.filter((task) => !done(task)).reduce((sum, t) => sum + t.hours, 0);
    return `| ${phase} | ${p0.filter(done).length} of ${p0.length} | ${
      p1.filter(done).length
    } of ${p1.length} | ${openHours} |`;
  });
  const p0All = tasks.filter((task) => task.priority === "P0");
  const p1All = tasks.filter((task) => task.priority === "P1");
  const openTotal = p0All.filter((task) => !done(task)).reduce((sum, t) => sum + t.hours, 0);
  const p0Done = p0All.filter(done).length;
  const readiness = p0All.length === 0 ? 0 : Math.round((p0Done / p0All.length) * 100);

  return [
    "| Phase | P0 done | P1 done | P0 hours left |",
    "|---|---|---|---|",
    ...rows,
    `| **Total** | **${p0Done} of ${p0All.length}** | **${p1All.filter(done).length} of ${
      p1All.length
    }** | **${openTotal}** |`,
    "",
    `**P0 readiness: ${readiness}% (${p0Done} of ${p0All.length} tasks).** Hours left are guesses, not commitments.`,
  ].join("\n");
}

function replaceBlock(content: string, block: string): string {
  const start = content.indexOf(START);
  const end = content.indexOf(END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`${ROADMAP} is missing the progress markers`);
  }
  const head = content.slice(0, start + START.length);
  const tail = content.slice(end);
  return `${head}\n${block}\n${tail}`;
}

function main(): void {
  const check = process.argv.includes("--check");
  const path = fileURLToPath(new URL(`../${ROADMAP}`, import.meta.url));
  const content = readFileSync(path, "utf8");
  const updated = replaceBlock(content, renderBlock(parseTasks(content.split("\n"))));

  if (check) {
    if (updated !== content) {
      console.error(
        `${ROADMAP} progress block is stale. Run \`pnpm roadmap\` and commit the result.`,
      );
      process.exit(1);
    }
    console.log(`${ROADMAP} progress block is current`);
    return;
  }
  writeFileSync(path, updated, "utf8");
  console.log(`${ROADMAP} progress block regenerated`);
}

if (process.argv[1]?.endsWith("roadmap-progress.ts")) {
  main();
}
